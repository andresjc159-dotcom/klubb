const dicts: Record<string, Record<string, string>> = { es, en };

function interpolate(str: string, params?: Record<string, any>): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? String(params[k]) : `{${k}}`));
}

export function useI18n() {
  const [lang, setLangState] = useState<string>(() => localStorage.getItem('klubb_lang') || 'es');

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: string) => {
    localStorage.setItem('klubb_lang', l);
    setLangState(l);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, any>) => {
      const dict = dicts[lang] || es;
      return interpolate(dict[key] ?? es[key] ?? key, params);
    },
    [lang],
  );

  return { t, lang, setLang };
}
